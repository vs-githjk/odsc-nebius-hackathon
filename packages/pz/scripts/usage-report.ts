import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { resolve, join } from "node:path";
import { fileURLToPath } from "node:url";
import { Trace } from "../src/schema/index.ts";

type Total = { calls: number; hits: number; prompt: number; completion: number; cached: number; credits: number; usd: number };
const empty = (): Total => ({ calls: 0, hits: 0, prompt: 0, completion: 0, cached: 0, credits: 0, usd: 0 });
const cell = (s: string) => s.replaceAll("|", "\\|").replace(/[\r\n]/g, " ");

export function usageReport(inputs: { path: string; trace: Trace }[]): string {
  if (inputs.some(({ trace }) => trace.synthetic || trace.mode === "SAMPLE")) throw new Error("Recorded traces required");
  if (new Set(inputs.map(({ trace }) => trace.id)).size !== inputs.length) throw new Error("Duplicate trace IDs");
  const groups = new Map<string, Total>(), perTrace = new Map<string, Total>();
  const add = (t: Total, row: Trace["usage"][number]) => {
    if (row.cacheHit) { t.hits++; return; }
    t.calls++; t.prompt += row.promptTokens; t.completion += row.completionTokens;
    t.cached += row.cachedTokens; t.credits += row.credits; t.usd += row.costUsd;
  };
  const total = empty();
  for (const { path, trace } of inputs) {
    const t = empty(); perTrace.set(path, t);
    for (const row of trace.usage) {
      const key = [row.service, row.endpoint, row.model ?? "none", row.step].map(cell).join(" | ");
      const g = groups.get(key) ?? empty(); groups.set(key, g);
      add(g, row); add(t, row); add(total, row);
    }
  }
  const headers = "Calls | Cache hits | Input tokens | Output tokens | Cached tokens | Credits | USD";
  const values = (t: Total) => `${t.calls} | ${t.hits} | ${t.prompt} | ${t.completion} | ${t.cached} | ${t.credits} | ${t.usd.toFixed(8)}`;
  const rate = total.calls + total.hits ? (100 * total.hits / (total.calls + total.hits)).toFixed(2) : "0.00";
  return ["# Recorded usage report", "", "Generated by `make usage-report` from the current committed E2 trace files. No provider requests are made.", "",
    "This is the usage represented by these saved traces, not the team billing ledger or all historical runs. Failed claims without traces, overwritten runs and unreported provider charges are absent. Failed attempts with usage rows remain included. Cache hits are counted separately and excluded from token, credit and dollar sums; cached input tokens on non-hit provider calls remain included.", "",
    `Recorded files: ${inputs.length}. Request cache-hit rate: ${rate}%.`, "", "## By service, endpoint, model and stage", "",
    `| Service | Endpoint | Model | Stage | ${headers} |`, "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ...[...groups].sort(([a], [b]) => a.localeCompare(b)).map(([key, t]) => `| ${key} | ${values(t)} |`),
    `| **Total** | | | | ${values(total)} |`, "", "## Per trace", "",
    `| Trace | ${headers} |`, "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ...[...perTrace].map(([path, t]) => `| [${cell(path)}](../${path}) | ${values(t)} |`), "",
    "## Why these services", "",
    "Token Factory Qwen chat supplies structured intake, fingerprints, query plans and typed evidence questions. Qwen embeddings support near-duplicate clustering and possible-number variants. Code applies the matching rules and decides the ending. Tavily search discovers candidate pages in date windows; extract reads their text. Wayback and publication registries supply independent date evidence. The rows above show which calls actually occur in this saved set; an unused stage is not counted as measured.", ""].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const dir = "eval/dev-traces";
  const inputs = readdirSync(dir).filter(name => /^dev-\d{2}\.json$/.test(name)).sort().map(name => {
    const path = join(dir, name);
    return { path, trace: Trace.parse(JSON.parse(readFileSync(path, "utf8"))) };
  });
  if (!inputs.length) throw new Error("No recorded dev traces");
  writeFileSync(resolve("docs/usage-report.md"), usageReport(inputs));
  console.log(`usage-report: ${inputs.length} recorded files -> docs/usage-report.md`);
}
